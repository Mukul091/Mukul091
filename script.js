const state = {
  lang: localStorage.getItem("health.lang") || "en",
  theme: localStorage.getItem("health.theme") || "dark",
  history: JSON.parse(localStorage.getItem("health.history") || "[]")
};

function t(key) {
  return TEXT[state.lang][key] || "";
}

function format(template, values) {
  return Object.entries(values).reduce(
    (acc, [key, value]) => acc.replaceAll(`{${key}}`, value),
    template
  );
}

function saveHistory(type, message) {
  const item = {
    type,
    message,
    timestamp: new Date().toISOString()
  };

  state.history.unshift(item);
  state.history = state.history.slice(0, 10);
  localStorage.setItem("health.history", JSON.stringify(state.history));
  renderHistory();
}

function renderHistory() {
  const list = document.getElementById("historyList");
  list.innerHTML = "";

  if (!state.history.length) {
    const li = document.createElement("li");
    li.className = "empty-history";
    li.textContent = t("historyEmpty");
    list.appendChild(li);
    return;
  }

  state.history.forEach((item) => {
    const li = document.createElement("li");
    const dt = new Date(item.timestamp);
    const label = item.type === "age" ? t("historyAge") : item.type === "bmi" ? t("historyBmi") : t("historyBmr");
    li.innerHTML = `<strong>${label}</strong> — ${item.message} <br/><small>${t("historyAt")} ${dt.toLocaleString()}</small>`;
    list.appendChild(li);
  });
}

function setResult(elementId, message) {
  document.getElementById(elementId).innerHTML = message;
}

function calculateAge() {
  const dobInput = document.getElementById("dob").value;

  if (!dobInput) {
    setResult("ageResult", t("warnDobMissing"));
    return;
  }

  const dob = new Date(dobInput);
  const today = new Date();

  if (dob > today) {
    setResult("ageResult", t("warnDobFuture"));
    return;
  }

  let years = today.getFullYear() - dob.getFullYear();
  let months = today.getMonth() - dob.getMonth();
  let days = today.getDate() - dob.getDate();

  if (days < 0) {
    months -= 1;
    const previousMonth = new Date(today.getFullYear(), today.getMonth(), 0);
    days += previousMonth.getDate();
  }

  if (months < 0) {
    years -= 1;
    months += 12;
  }

  const message = format(t("ageResult"), { years, months, days });
  setResult("ageResult", message);
  saveHistory("age", `${years}y ${months}m ${days}d`);
}

function calculateBMI() {
  const height = parseFloat(document.getElementById("height").value);
  const weight = parseFloat(document.getElementById("weight").value);

  if (!height || !weight || height <= 0 || weight <= 0) {
    setResult("bmiResult", t("warnBmiInvalid"));
    return;
  }

  const bmi = weight / ((height / 100) * (height / 100));
  const roundedBMI = bmi.toFixed(1);

  let category = "";
  let tip = "";

  if (bmi < 18.5) {
    category = t("underweight");
    tip = t("tipUnderweight");
  } else if (bmi < 25) {
    category = t("normal");
    tip = t("tipNormal");
  } else if (bmi < 30) {
    category = t("overweight");
    tip = t("tipOverweight");
  } else {
    category = t("obese");
    tip = t("tipObese");
  }

  const message = format(t("bmiResult"), { bmi: roundedBMI, category, tip });
  setResult("bmiResult", message);
  saveHistory("bmi", `${roundedBMI} (${category})`);
}

function calculateBMR() {
  const gender = document.getElementById("gender").value;
  const age = parseFloat(document.getElementById("age").value);
  const height = parseFloat(document.getElementById("bmrHeight").value);
  const weight = parseFloat(document.getElementById("bmrWeight").value);

  if (!age || !height || !weight || age <= 0 || height <= 0 || weight <= 0) {
    setResult("bmrResult", t("warnBmrInvalid"));
    return;
  }

  let bmr;
  if (gender === "male") {
    bmr = 10 * weight + 6.25 * height - 5 * age + 5;
  } else {
    bmr = 10 * weight + 6.25 * height - 5 * age - 161;
  }

  const maintenance = (bmr * 1.55).toFixed(0);
  const message = format(t("bmrResult"), { bmr: bmr.toFixed(0), maintenance });
  setResult("bmrResult", message);
  saveHistory("bmr", `${bmr.toFixed(0)} / ${maintenance} kcal`);
}

function applyTheme() {
  document.body.setAttribute("data-theme", state.theme);
  const themeBtn = document.getElementById("themeToggle");
  themeBtn.textContent = state.theme === "dark" ? t("themeLight") : t("themeDark");
}

function applyLanguage() {
  document.documentElement.lang = t("pageLang");
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (key === "heroTitle" || key === "heroSubtitle") {
      element.innerHTML = t(key);
    } else {
      element.textContent = t(key);
    }
  });

  document.getElementById("langToggle").textContent = t("langToggle");
  applyTheme();
  renderHistory();
}

function toggleTheme() {
  state.theme = state.theme === "dark" ? "light" : "dark";
  localStorage.setItem("health.theme", state.theme);
  applyTheme();
}

function toggleLanguage() {
  state.lang = state.lang === "en" ? "bn" : "en";
  localStorage.setItem("health.lang", state.lang);
  applyLanguage();
}

function clearHistory() {
  state.history = [];
  localStorage.setItem("health.history", "[]");
  renderHistory();
}

document.getElementById("ageBtn").addEventListener("click", calculateAge);
document.getElementById("bmiBtn").addEventListener("click", calculateBMI);
document.getElementById("bmrBtn").addEventListener("click", calculateBMR);
document.getElementById("themeToggle").addEventListener("click", toggleTheme);
document.getElementById("langToggle").addEventListener("click", toggleLanguage);
document.getElementById("clearHistoryBtn").addEventListener("click", clearHistory);

applyLanguage();
applyTheme();
renderHistory();
